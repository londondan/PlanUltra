export function textRects(
  txt: string,
  ox: number,
  oy: number,
  fill: string
): [string[], number] {
  const rects: string[] = []
  let x = ox
  for (const ch of txt) {
    if (ch === ' ') { x += 4; continue }
    const g = FONT[ch]
    if (!g) { x += 6; continue }
    for (let r = 0; r < g.length; r++) {
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] === '1') {
          rects.push(`<rect x="${x + c}" y="${oy + r}" width="1" height="1" fill="${fill}"/>`)
        }
      }
    }
    x += 6
  }
  return [rects, x - ox - 1]
}
